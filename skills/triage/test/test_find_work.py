def run(case, issues, fault, labels, tools):
    with tempfile.TemporaryDirectory() as tmp:
        d = pathlib.Path(tmp)
        bin_dir = d / "bin"
        bin_dir.mkdir()
        if tools != "no gh":
            gh = bin_dir / "gh"
            gh.write_text(f'#!/bin/sh\nexec "{sys.executable}" -I "{FAKE}" "$@"\n')
            gh.chmod(0o755)
        for tool in ["jq", "awk"]:
            if tool == "jq" and tools == "no jq":
                continue
            real = shutil.which(tool)
            if real is None:
                raise RuntimeError(f"{tool} is not installed here, so the test can't run")
            (bin_dir / tool).symlink_to(real)
        scenario = d / "scenario.json"
        scenario.write_text(json.dumps({"issues": issues, "fault": fault}))
        args = ["/bin/sh", str(SCRIPT)]
        if labels is not None:
            (d / "labels.md").write_text(labels)
            args.append(str(d / "labels.md"))
        else:
            args.append(str(d / "missing.md"))
        env = {"PATH": str(bin_dir), "FAKE_GH_SCENARIO": str(scenario), "LC_ALL": "C"}
        return subprocess.run(args, cwd=d, env=env, capture_output=True, text=True, timeout=120)


def main():
    for case, what, issues, fault, labels, tools, code, out, err in CASES:
        try:
            r = run(case, issues, fault, labels, tools)
        except (OSError, RuntimeError, subprocess.TimeoutExpired) as e:
            fail(case, f"{what}: the case could not run: {e}")
            continue
        got = r.stdout.splitlines()
        if r.returncode != code:
            fail(case, f"{what}: exit {r.returncode}, not {code} (stderr: {r.stderr.strip()!r})")
        if got != out:
            fail(case, f"{what}: printed {got!r}, not {out!r}")
        if code == 0 and r.stderr:
            fail(case, f"{what}: wrote to stderr: {r.stderr.strip()!r}")
        if code != 0 and (err is None or err not in r.stderr):
            fail(case, f"{what}: stderr {r.stderr.strip()!r} does not say {err!r}")


main()
