def fail(case, why):
    failures.append(f"FAIL {case} {why}")


def labels_md(rows):
    """A labels file in setup's format, from (role, label) rows."""
    lines = ["# Triage labels", "", "| Role | Label here | Meaning |", "| --- | --- | --- |"]
    lines += [f"| `{role}` | {label} | Synthetic meaning |" for role, label in rows]
    return "\n".join(lines) + "\n"


DEFAULT = labels_md([(r, f"`{r}`") for r in ROLES])


def issue(n, title=None, labels=(), milestone=False, parent=None, sub_issues=0, comments=(),
          state="OPEN", created=None):
    return {"number": n, "title": title or f"Synthetic issue {n}", "state": state,
            "created": n if created is None else created, "milestone": milestone, "parent": parent,
            "sub_issues": sub_issues, "labels": list(labels), "comments": list(comments)}


def sorted_issues(count):
    """Issues already sorted and waiting for approval: never triage work."""
    return [issue(n, labels=["ready-for-agent", "enhancement"]) for n in range(1, count + 1)]


