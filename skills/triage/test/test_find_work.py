"""The test of find-work.sh, through a fake `gh` (fake_gh.py) that serves
synthetic issues the way GitHub does: 100 a page at most, only the comments
and labels the query asks for, and the faults a real read can hit.

Each case runs find-work.sh in a scratch folder whose PATH holds only the
fake `gh`, `jq` and `awk`, so the real `gh` is never reached. It asserts the
exit code, the exact output, and for a failed read (exit 2) an empty output
and the reason on stderr. Any other result is a failure with its case id.

Prints one "FAIL <id> ..." line per failure, then "PASS: 0 failed check(s)"
(exit 0) or "FAIL: <n> failed check(s)" (exit 1).

Usage: python3 -I test_find_work.py
"""

